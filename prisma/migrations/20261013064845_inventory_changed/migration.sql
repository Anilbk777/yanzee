-- Data-preserving inventory schema migration for PostgreSQL / Neon.
-- Target Prisma models: OutletStock, StockBatch, StockMovement, StockMovementItem.
--
-- IMPORTANT:
--   1. Review this file against the exact live schema before running it on production.
--   2. This migration archives the old inventory rows as JSONB in the separate
--      inventory_legacy_archive schema before reshaping or dropping old tables/columns.
--   3. Existing stock_movements are retained and their old item fields are copied into
--      stock_movement_items where a valid batch_id exists.
--   4. Old SALE and SALE_RESTORE types are mapped to STOCK_OUT and STOCK_RESTORE.
--   5. StockStatus values are recalculated from quantity: <= 0 OUT_OF_STOCK, 1..9
--      LOW_STOCK, >= 10 IN_STOCK.
--   6. If a required relationship cannot be inferred, original row JSON remains in the
--      archive and the migration raises an error instead of inventing a relationship.

BEGIN;

-- -----------------------------------------------------------------------------
-- 0. Archive every old inventory row before modifying or dropping anything.
--    This schema is deliberately outside public so Prisma's public-schema models
--    do not own or manage the archive tables.
-- -----------------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS inventory_legacy_archive;

CREATE TABLE IF NOT EXISTS inventory_legacy_archive.records (
    archive_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_table TEXT NOT NULL,
    source_id    TEXT,
    archived_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    row_data     JSONB NOT NULL
);

DO $archive$
BEGIN
    IF to_regclass('public.stock_batches') IS NOT NULL THEN
        INSERT INTO inventory_legacy_archive.records(source_table, source_id, row_data)
        SELECT 'stock_batches', t.id::text, to_jsonb(t) FROM public.stock_batches AS t;
    END IF;
    IF to_regclass('public.stock_movements') IS NOT NULL THEN
        INSERT INTO inventory_legacy_archive.records(source_table, source_id, row_data)
        SELECT 'stock_movements', t.id::text, to_jsonb(t) FROM public.stock_movements AS t;
    END IF;
    IF to_regclass('public.stock_movement_items') IS NOT NULL THEN
        INSERT INTO inventory_legacy_archive.records(source_table, source_id, row_data)
        SELECT 'stock_movement_items', t.id::text, to_jsonb(t) FROM public.stock_movement_items AS t;
    END IF;
    IF to_regclass('public.stock_receipts') IS NOT NULL THEN
        INSERT INTO inventory_legacy_archive.records(source_table, source_id, row_data)
        SELECT 'stock_receipts', t.id::text, to_jsonb(t) FROM public.stock_receipts AS t;
    END IF;
    IF to_regclass('public.stock_transfers') IS NOT NULL THEN
        INSERT INTO inventory_legacy_archive.records(source_table, source_id, row_data)
        SELECT 'stock_transfers', t.id::text, to_jsonb(t) FROM public.stock_transfers AS t;
    END IF;
    IF to_regclass('public.stock_transfer_items') IS NOT NULL THEN
        INSERT INTO inventory_legacy_archive.records(source_table, source_id, row_data)
        SELECT 'stock_transfer_items', t.id::text, to_jsonb(t) FROM public.stock_transfer_items AS t;
    END IF;
    IF to_regclass('public.outlet_stocks') IS NOT NULL THEN
        INSERT INTO inventory_legacy_archive.records(source_table, source_id, row_data)
        SELECT 'outlet_stocks', t.id::text, to_jsonb(t) FROM public.outlet_stocks AS t;
    END IF;
END
$archive$;

