-- -----------------------------------------------------------------------------
-- 10. New foreign keys. Use guarded creation so a pre-existing equivalent FK is
--     not duplicated in databases with part of the new design already applied.
-- -----------------------------------------------------------------------------
DO $foreign_keys$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'outlet_stocks_store_id_fkey' AND conrelid = 'public.outlet_stocks'::regclass) THEN
        ALTER TABLE public.outlet_stocks ADD CONSTRAINT outlet_stocks_store_id_fkey
            FOREIGN KEY (store_id) REFERENCES public.stores(id) ON DELETE CASCADE ON UPDATE CASCADE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'outlet_stocks_outlet_id_fkey' AND conrelid = 'public.outlet_stocks'::regclass) THEN
        ALTER TABLE public.outlet_stocks ADD CONSTRAINT outlet_stocks_outlet_id_fkey
            FOREIGN KEY (outlet_id) REFERENCES public.outlets(id) ON DELETE CASCADE ON UPDATE CASCADE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'outlet_stocks_product_id_store_id_fkey' AND conrelid = 'public.outlet_stocks'::regclass) THEN
        ALTER TABLE public.outlet_stocks ADD CONSTRAINT outlet_stocks_product_id_store_id_fkey
            FOREIGN KEY (product_id, store_id) REFERENCES public.products(id, store_id) ON DELETE CASCADE ON UPDATE CASCADE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'outlet_stocks_variant_id_fkey' AND conrelid = 'public.outlet_stocks'::regclass) THEN
        ALTER TABLE public.outlet_stocks ADD CONSTRAINT outlet_stocks_variant_id_fkey
            FOREIGN KEY (variant_id) REFERENCES public.product_variants(id) ON DELETE CASCADE ON UPDATE CASCADE;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'stock_batches_movement_id_fkey' AND conrelid = 'public.stock_batches'::regclass) THEN
        ALTER TABLE public.stock_batches ADD CONSTRAINT stock_batches_movement_id_fkey
            FOREIGN KEY (movement_id) REFERENCES public.stock_movements(id) ON DELETE RESTRICT ON UPDATE CASCADE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'stock_movements_other_outlet_id_fkey' AND conrelid = 'public.stock_movements'::regclass) THEN
        ALTER TABLE public.stock_movements ADD CONSTRAINT stock_movements_other_outlet_id_fkey
            FOREIGN KEY (other_outlet_id) REFERENCES public.outlets(id) ON DELETE RESTRICT ON UPDATE CASCADE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'stock_movements_corrects_movement_id_fkey' AND conrelid = 'public.stock_movements'::regclass) THEN
        ALTER TABLE public.stock_movements ADD CONSTRAINT stock_movements_corrects_movement_id_fkey
            FOREIGN KEY (corrects_movement_id) REFERENCES public.stock_movements(id) ON DELETE RESTRICT ON UPDATE CASCADE;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'stock_movement_items_movement_id_fkey' AND conrelid = 'public.stock_movement_items'::regclass) THEN
        ALTER TABLE public.stock_movement_items ADD CONSTRAINT stock_movement_items_movement_id_fkey
            FOREIGN KEY (movement_id) REFERENCES public.stock_movements(id) ON DELETE RESTRICT ON UPDATE CASCADE;
    END IF;
