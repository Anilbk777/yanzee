-- -----------------------------------------------------------------------------
-- 7. Fill new movement totals and infer the movement that originally created each
--    batch. Prefer receipt + product matching, then an existing batch link.
-- -----------------------------------------------------------------------------
UPDATE public.stock_movements
SET total_quantity = CASE
        WHEN type::text = 'ADJUSTMENT' THEN COALESCE(quantity, 0)
        ELSE ABS(COALESCE(quantity, 0))
    END,
    total_cost = CASE
        WHEN type::text = 'ADJUSTMENT' THEN COALESCE(quantity, 0) * COALESCE(unit_cost, 0)
        ELSE ABS(COALESCE(quantity, 0)) * COALESCE(unit_cost, 0)
    END,
    total_products = CASE WHEN product_id IS NULL THEN 0 ELSE 1 END
WHERE total_quantity IS NULL OR total_cost IS NULL OR total_products IS NULL;

-- Map legacy transfer counterpart outlets while stock_transfers still exists.
DO $transfer_mapping$
BEGIN
    IF to_regclass('public.stock_transfers') IS NOT NULL THEN
        UPDATE public.stock_movements AS m
        SET other_outlet_id = CASE
            WHEN m.type::text = 'TRANSFER_OUT' THEN t.to_outlet_id
            WHEN m.type::text = 'TRANSFER_IN'  THEN t.from_outlet_id
            ELSE m.other_outlet_id
        END
        FROM public.stock_transfers AS t
        WHERE m.transfer_id = t.id
          AND m.type::text IN ('TRANSFER_OUT', 'TRANSFER_IN')
          AND m.other_outlet_id IS NULL;
    END IF;
END
$transfer_mapping$;

-- First match the receipt and the same product/variant.
UPDATE public.stock_batches AS b
SET movement_id = (
    SELECT m.id
    FROM public.stock_movements AS m
    WHERE b.receipt_id IS NOT NULL
      AND m.receipt_id = b.receipt_id
      AND m.store_id = b.store_id
      AND m.product_id = b.product_id
      AND m.variant_id IS NOT DISTINCT FROM b.variant_id
      AND m.type::text IN ('STOCK_IN', 'TRANSFER_IN', 'ADJUSTMENT')
    ORDER BY m.created_at, m.id
    LIMIT 1
)
WHERE b.movement_id IS NULL
  AND b.receipt_id IS NOT NULL
  AND EXISTS (
    SELECT 1 FROM public.stock_movements AS m
    WHERE m.receipt_id = b.receipt_id
      AND m.store_id = b.store_id
      AND m.product_id = b.product_id
      AND m.variant_id IS NOT DISTINCT FROM b.variant_id
      AND m.type::text IN ('STOCK_IN', 'TRANSFER_IN', 'ADJUSTMENT')
  );

-- If receipt matching did not work, use an existing movement batch link.
UPDATE public.stock_batches AS b
SET movement_id = (
    SELECT m.id
    FROM public.stock_movements AS m
    WHERE m.batch_id = b.id
      AND m.store_id = b.store_id
      AND m.product_id = b.product_id
      AND m.variant_id IS NOT DISTINCT FROM b.variant_id
    ORDER BY CASE WHEN m.type::text IN ('STOCK_IN', 'TRANSFER_IN', 'ADJUSTMENT') THEN 0 ELSE 1 END,
             m.created_at, m.id
    LIMIT 1
)
WHERE b.movement_id IS NULL
  AND EXISTS (
    SELECT 1 FROM public.stock_movements AS m
    WHERE m.batch_id = b.id
      AND m.store_id = b.store_id
      AND m.product_id = b.product_id
      AND m.variant_id IS NOT DISTINCT FROM b.variant_id
  );

-- Any remaining batch had no suitable creation movement. Create a historical
-- STOCK_IN row for it, explicitly linked to that batch, rather than dropping it.
WITH batches_without_movement AS (
    SELECT b.*
    FROM public.stock_batches AS b
    WHERE b.movement_id IS NULL
), inserted_movements AS (
    INSERT INTO public.stock_movements (
        id, store_id, type, outlet_id, batch_id, product_id, variant_id,
        quantity, unit_cost, receipt_id, total_quantity, total_cost,
        total_products, created_at
    )
    SELECT
        gen_random_uuid()::text,
        b.store_id,
        'STOCK_IN'::"MovementType",
        b.outlet_id,
        b.id,
        b.product_id,
        b.variant_id,
        GREATEST(COALESCE(b.quantity, 1), 1),
        COALESCE(b.unit_cost, 0),
        b.receipt_id,
        GREATEST(COALESCE(b.quantity, 1), 1),
        GREATEST(COALESCE(b.quantity, 1), 1) * COALESCE(b.unit_cost, 0),
        1,
        COALESCE(b.created_at, CURRENT_TIMESTAMP)
    FROM batches_without_movement AS b
    RETURNING id, batch_id
)
UPDATE public.stock_batches AS b
SET movement_id = i.id
FROM inserted_movements AS i
WHERE b.id = i.batch_id
  AND b.movement_id IS NULL;

-- Do not continue if a batch still cannot be linked.
DO $assert_batch_movement$
BEGIN
    IF EXISTS (SELECT 1 FROM public.stock_batches WHERE movement_id IS NULL) THEN
        RAISE EXCEPTION 'Inventory migration stopped: some stock_batches could not be assigned a movement_id';
    END IF;
END
$assert_batch_movement$;

-- Convert the legacy batch number (which may have been a string) to a unique,
-- deterministic integer per store. The previous value is retained in the archive.
WITH ranked AS (
    SELECT id,
           ROW_NUMBER() OVER (PARTITION BY store_id ORDER BY created_at NULLS FIRST, id) AS new_number
    FROM public.stock_batches
)
UPDATE public.stock_batches AS b
SET batch_number__new = ranked.new_number::integer
FROM ranked
WHERE ranked.id = b.id;

-- -----------------------------------------------------------------------------
-- 8. Create the normalized movement-line table, then backfill it from old movement
--    rows where an actual batch relation exists. Rows without a batch remain fully
--    available in the JSON archive and their event totals remain on stock_movements.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.stock_movement_items (
    id TEXT NOT NULL,
    movement_id TEXT NOT NULL,
    store_id TEXT NOT NULL,
    outlet_id TEXT NOT NULL,
    type "MovementType" NOT NULL,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    batch_id TEXT NOT NULL,
    product_id TEXT NOT NULL,
    variant_id TEXT,
    quantity INTEGER NOT NULL,
    unit_cost DECIMAL(12,2) NOT NULL,
    CONSTRAINT stock_movement_items_pkey PRIMARY KEY (id)
);

INSERT INTO public.stock_movement_items (
    id, movement_id, store_id, outlet_id, type, created_at,
    batch_id, product_id, variant_id, quantity, unit_cost
)
SELECT
    gen_random_uuid()::text,
    m.id,
    m.store_id,
    m.outlet_id,
    m.type,
    COALESCE(m.created_at, CURRENT_TIMESTAMP),
    m.batch_id,
    m.product_id,
    m.variant_id,
    CASE
        WHEN m.type::text = 'ADJUSTMENT' THEN COALESCE(m.quantity, 0)
        ELSE ABS(COALESCE(m.quantity, 0))
    END,
    COALESCE(m.unit_cost, 0)
FROM public.stock_movements AS m
JOIN public.stock_batches AS b ON b.id = m.batch_id
WHERE m.batch_id IS NOT NULL
  AND m.product_id IS NOT NULL
  AND NOT EXISTS (
      SELECT 1
      FROM public.stock_movement_items AS i
      WHERE i.movement_id = m.id
        AND i.batch_id = m.batch_id
        AND i.product_id = m.product_id
        AND i.variant_id IS NOT DISTINCT FROM m.variant_id
  );

-- Required batch fields are set only after backfills are complete.
ALTER TABLE public.stock_batches ALTER COLUMN movement_id SET NOT NULL;
ALTER TABLE public.stock_batches DROP COLUMN IF EXISTS batch_number;
ALTER TABLE public.stock_batches RENAME COLUMN batch_number__new TO batch_number;
ALTER TABLE public.stock_batches ALTER COLUMN batch_number SET NOT NULL;

-- Keep the store's next sequence above every migrated batch number.
ALTER TABLE public.stores
    ADD COLUMN IF NOT EXISTS next_batch_number INTEGER NOT NULL DEFAULT 1;

UPDATE public.stores AS s
SET next_batch_number = COALESCE((
    SELECT MAX(b.batch_number) + 1
    FROM public.stock_batches AS b
    WHERE b.store_id = s.id
), 1);

