-- -----------------------------------------------------------------------------
-- 12. Database rules. NOT VALID preserves existing historical rows that may not
--     satisfy newly introduced rules, while enforcing each rule for new/updated rows.
-- -----------------------------------------------------------------------------
DO $checks$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_outlet_stock_qty' AND conrelid = 'public.outlet_stocks'::regclass) THEN
        ALTER TABLE public.outlet_stocks ADD CONSTRAINT ck_outlet_stock_qty
            CHECK (quantity >= 0 AND expired_quantity >= 0) NOT VALID;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_outlet_stock_key' AND conrelid = 'public.outlet_stocks'::regclass) THEN
        ALTER TABLE public.outlet_stocks ADD CONSTRAINT ck_outlet_stock_key
            CHECK (item_key = COALESCE(variant_id, product_id)) NOT VALID;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_product_qty' AND conrelid = 'public.products'::regclass) THEN
        ALTER TABLE public.products ADD CONSTRAINT ck_product_qty CHECK (quantity >= 0) NOT VALID;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_variant_qty' AND conrelid = 'public.product_variants'::regclass) THEN
        ALTER TABLE public.product_variants ADD CONSTRAINT ck_variant_qty CHECK (quantity >= 0) NOT VALID;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_batch_qty' AND conrelid = 'public.stock_batches'::regclass) THEN
        ALTER TABLE public.stock_batches ADD CONSTRAINT ck_batch_qty
            CHECK (quantity > 0 AND remaining_quantity >= 0 AND remaining_quantity <= quantity) NOT VALID;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_batch_dates' AND conrelid = 'public.stock_batches'::regclass) THEN
        ALTER TABLE public.stock_batches ADD CONSTRAINT ck_batch_dates
            CHECK (manufacture_date IS NULL OR expiry_date IS NULL OR manufacture_date <= expiry_date) NOT VALID;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_item_qty' AND conrelid = 'public.stock_movement_items'::regclass) THEN
        ALTER TABLE public.stock_movement_items ADD CONSTRAINT ck_item_qty
            CHECK ((type = 'ADJUSTMENT' AND quantity <> 0) OR (type <> 'ADJUSTMENT' AND quantity > 0)) NOT VALID;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_movement_transfer' AND conrelid = 'public.stock_movements'::regclass) THEN
        ALTER TABLE public.stock_movements ADD CONSTRAINT ck_movement_transfer CHECK (
            (type IN ('TRANSFER_OUT', 'TRANSFER_IN')
             AND transfer_id IS NOT NULL
             AND other_outlet_id IS NOT NULL
             AND other_outlet_id <> outlet_id)
            OR type NOT IN ('TRANSFER_OUT', 'TRANSFER_IN')
        ) NOT VALID;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_movement_order' AND conrelid = 'public.stock_movements'::regclass) THEN
        ALTER TABLE public.stock_movements ADD CONSTRAINT ck_movement_order
            CHECK (type NOT IN ('STOCK_OUT', 'STOCK_RESTORE') OR order_id IS NOT NULL) NOT VALID;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_movement_note' AND conrelid = 'public.stock_movements'::regclass) THEN
        ALTER TABLE public.stock_movements ADD CONSTRAINT ck_movement_note
            CHECK (type NOT IN ('ADJUSTMENT', 'WRITE_OFF') OR (note IS NOT NULL AND length(btrim(note)) > 0)) NOT VALID;
    END IF;
END
$checks$;

-- -----------------------------------------------------------------------------
-- 13. Derive stock_status from live quantities and install the triggers.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.set_stock_status() RETURNS trigger AS $$
BEGIN
    NEW.stock_status := (
        CASE
            WHEN NEW.quantity <= 0 THEN 'OUT_OF_STOCK'
            WHEN NEW.quantity < 10 THEN 'LOW_STOCK'
            ELSE 'IN_STOCK'
        END
    )::"StockStatus";
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

UPDATE public.products
SET stock_status = CASE
    WHEN quantity <= 0 THEN 'OUT_OF_STOCK'::"StockStatus"
    WHEN quantity < 10 THEN 'LOW_STOCK'::"StockStatus"
    ELSE 'IN_STOCK'::"StockStatus"
END;

UPDATE public.product_variants
SET stock_status = CASE
    WHEN quantity <= 0 THEN 'OUT_OF_STOCK'::"StockStatus"
    WHEN quantity < 10 THEN 'LOW_STOCK'::"StockStatus"
    ELSE 'IN_STOCK'::"StockStatus"
END;

UPDATE public.outlet_stocks
SET stock_status = CASE
    WHEN quantity <= 0 THEN 'OUT_OF_STOCK'::"StockStatus"
    WHEN quantity < 10 THEN 'LOW_STOCK'::"StockStatus"
    ELSE 'IN_STOCK'::"StockStatus"
END;

CREATE TRIGGER trg_outlet_stocks_status
    BEFORE INSERT OR UPDATE OF quantity ON public.outlet_stocks
    FOR EACH ROW EXECUTE FUNCTION public.set_stock_status();
CREATE TRIGGER trg_products_status
    BEFORE INSERT OR UPDATE OF quantity ON public.products
    FOR EACH ROW EXECUTE FUNCTION public.set_stock_status();
CREATE TRIGGER trg_product_variants_status
    BEFORE INSERT OR UPDATE OF quantity ON public.product_variants
    FOR EACH ROW EXECUTE FUNCTION public.set_stock_status();

COMMIT;

