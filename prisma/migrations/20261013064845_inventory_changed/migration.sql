-- -----------------------------------------------------------------------------
-- 4. Convert MovementType safely.
--    Crucially, only alter stock_movement_items if it already exists. The new
--    table is created AFTER this enum is replaced, so there is no reference to a
--    table that has not been created yet (the original P3006 / 42P01 cause).
-- -----------------------------------------------------------------------------
ALTER TABLE public.stock_movements ALTER COLUMN type DROP DEFAULT;
CREATE TYPE "MovementType_new" AS ENUM (
    'STOCK_IN', 'STOCK_OUT', 'STOCK_RESTORE', 'TRANSFER_OUT', 'TRANSFER_IN', 'WRITE_OFF', 'ADJUSTMENT'
);

ALTER TABLE public.stock_movements
    ALTER COLUMN type TYPE "MovementType_new"
    USING (
        CASE type::text
            WHEN 'SALE' THEN 'STOCK_OUT'
            WHEN 'SALE_RESTORE' THEN 'STOCK_RESTORE'
            ELSE type::text
        END
    )::"MovementType_new";

DO $movement_items_enum$
BEGIN
    IF to_regclass('public.stock_movement_items') IS NOT NULL
       AND EXISTS (
           SELECT 1 FROM information_schema.columns
           WHERE table_schema = 'public'
             AND table_name = 'stock_movement_items'
             AND column_name = 'type'
       ) THEN
        EXECUTE 'ALTER TABLE public.stock_movement_items ALTER COLUMN type DROP DEFAULT';
        EXECUTE $sql$
            ALTER TABLE public.stock_movement_items
            ALTER COLUMN type TYPE "MovementType_new"
            USING (
                CASE type::text
                    WHEN 'SALE' THEN 'STOCK_OUT'
                    WHEN 'SALE_RESTORE' THEN 'STOCK_RESTORE'
                    ELSE type::text
                END
            )::"MovementType_new"
        $sql$;
    END IF;
END
$movement_items_enum$;

ALTER TYPE "MovementType" RENAME TO "MovementType_old";
ALTER TYPE "MovementType_new" RENAME TO "MovementType";
DROP TYPE "MovementType_old";

-- -----------------------------------------------------------------------------
-- 5. Convert StockStatus based on quantity, rather than casting removed labels.
--    This safely handles EXPIRING_SOON and DEAD_STOCK because those are report
--    classifications, not the current sellable-stock status.
-- -----------------------------------------------------------------------------
CREATE TYPE "StockStatus_new" AS ENUM ('IN_STOCK', 'LOW_STOCK', 'OUT_OF_STOCK');

DO $stock_status_enum$
DECLARE
    t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['outlet_stocks', 'products', 'product_variants'] LOOP
        IF EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'public'
              AND table_name = t
              AND column_name = 'stock_status'
        ) THEN
            EXECUTE format('ALTER TABLE public.%I ALTER COLUMN stock_status DROP DEFAULT', t);
            EXECUTE format(
                'ALTER TABLE public.%I ALTER COLUMN stock_status TYPE "StockStatus_new" USING '
                || '(CASE WHEN COALESCE(quantity, 0) <= 0 THEN ''OUT_OF_STOCK'' '
                || 'WHEN quantity < 10 THEN ''LOW_STOCK'' ELSE ''IN_STOCK'' END)::"StockStatus_new"', t
            );
        END IF;
    END LOOP;
END
$stock_status_enum$;

ALTER TYPE "StockStatus" RENAME TO "StockStatus_old";
ALTER TYPE "StockStatus_new" RENAME TO "StockStatus";
DROP TYPE "StockStatus_old";

